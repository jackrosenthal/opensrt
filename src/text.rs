//! The keys of the game's text, from its `.eng` string tables.
//!
//! Every key the code asks for is named once here, so a typo fails to
//! compile rather than showing the raw key on screen. Keys that come from
//! the game's own data files (a building's name, say) are looked up by
//! string with `Strings::lookup`.

use std::borrow::Cow;

/// Anything that names a string-table entry.
pub trait TextKey {
    fn key(&self) -> Cow<'static, str>;
}

/// The survey cursor's rating of a slope, 0 for the gentlest
/// (`SURVEY_CURSOR_RAITING_n`, spelled as in the tables).
pub struct SurveyRating(pub usize);

impl TextKey for SurveyRating {
    fn key(&self) -> Cow<'static, str> {
        Cow::Owned(format!("SURVEY_CURSOR_RAITING_{}", self.0))
    }
}

macro_rules! texts {
    ($($name:ident = $key:literal,)*) => {
        /// A fixed entry in the string tables.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        pub enum Text {
            $($name,)*
        }

        impl Text {
            pub const fn key(self) -> &'static str {
                match self {
                    $(Text::$name => $key,)*
                }
            }
        }
    };
}

impl<T: TextKey> TextKey for &T {
    fn key(&self) -> Cow<'static, str> {
        (*self).key()
    }
}

impl TextKey for Text {
    fn key(&self) -> Cow<'static, str> {
        Cow::Borrowed(Text::key(*self))
    }
}

